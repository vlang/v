module main

// Port of raylib textures_raw_data.c
// PORT NOTE: gg has no LoadImageRaw() helper. The fudesumi.raw data is
// replaced by a procedurally generated checked image, and the second checked
// texture is generated on the CPU as in the original example.
import gg

const raw_raywhite = gg.Color{245, 245, 245, 255}
const raw_brown = gg.Color{165, 42, 42, 255}

fn pixel(img gg.Image, x int, y int) gg.Color {
	if img.data == unsafe { nil } || x < 0 || y < 0 || x >= img.width || y >= img.height {
		return gg.Color{}
	}
	d := unsafe { &u8(img.data) }
	i := (y * img.width + x) * 4
	return gg.Color{d[i], d[i + 1], d[i + 2], d[i + 3]}
}

fn cache_raw(ctx &gg.Context, img gg.Image) int {
	mut copy := img
	copy.nr_channels = 4
	copy.init_sokol_image()
	return ctx.cache_image(copy)
}

struct App {
mut:
	ctx         &gg.Context = unsafe { nil }
	checked_idx int         = -1
	checked_w   int         = 960
	checked_h   int         = 480
}

fn init(data voidptr) {
	mut app := unsafe { &App(data) }
	mut pixels := []u8{len: app.checked_w * app.checked_h * 4}
	orange := gg.hex(0xffa500ff)
	gold := gg.hex(0xffd700ff)
	for y in 0 .. app.checked_h {
		for x in 0 .. app.checked_w {
			c := if ((x / 32 + y / 32) % 2) == 0 { orange } else { gold }
			i := (y * app.checked_w + x) * 4
			unsafe {
				pixels[i] = c.r
				pixels[i + 1] = c.g
				pixels[i + 2] = c.b
				pixels[i + 3] = c.a
			}
		}
	}
	app.checked_idx = cache_raw(app.ctx, gg.Image{
		width:       app.checked_w
		height:      app.checked_h
		nr_channels: 4
		ok:          true
		data:        pixels.data
	})
}

fn frame(data voidptr) {
	mut app := unsafe { &App(data) }
	app.ctx.begin()
	if app.checked_idx >= 0 {
		app.ctx.draw_image_with_config(
			img_id:   app.checked_idx
			img_rect: gg.Rect{400 - f32(app.checked_w) / 2, 225 - f32(app.checked_h) / 2, f32(app.checked_w), f32(app.checked_h)}
			color:    gg.Color{255, 255, 255, 128}
		)
	}
	app.ctx.draw_text(84, 85, 'CHECKED TEXTURE ', size: 30, color: raw_brown)
	app.ctx.draw_text(72, 148, 'GENERATED by CODE', size: 30, color: raw_brown)
	app.ctx.draw_text(46, 210, 'and RAW IMAGE LOADING', size: 30, color: raw_brown)
	app.ctx.draw_text(310, 430, '(c) Fudesumi sprite by Eiden Marsal', size: 10, color: raw_brown)
	app.ctx.end()
}

fn main() {
	mut app := &App{}
	app.ctx = gg.new_context(
		width:        800
		height:       450
		window_title: 'raylib [textures] example - raw data'
		user_data:    app
		init_fn:      init
		frame_fn:     frame
		bg_color:     raw_raywhite
	)
	app.ctx.run()
}
