module windows

import os
import yaml

const minimum_powershell_version = '7.4'

struct Step {
	id     string
	name   string
	script string
	env    map[string]string
}

struct Job {
	compiler string
	env      map[string]string
	steps    []Step
}

fn read_job(root string, compiler string) !Job {
	if compiler !in ['tcc', 'gcc', 'msvc'] {
		return error('Unknown Windows compiler: ${compiler}')
	}
	doc := yaml.parse_file(os.join_path(root, '.github', 'workflows', 'windows_ci_${compiler}.yml'))!
	job := doc.value_opt('jobs.${compiler}-windows')!
	mut steps := []Step{}
	for value in job.value('steps').array() {
		step := value.as_map()
		if 'run' !in step || 'id' !in step {
			continue
		}
		// Provisioning belongs to the installed VM, and MSYS2 graphics checks
		// require the hosted runner's separate MSYS2 setup action.
		id := (step['id'] or { return error('Missing step id') }).string()
		if id in ['install_openssl', 'install_dependencies', 'build', 'build_with_makev_bat_tcc',
			'show_tool_versions', 'verify_msvc_tools'] {
			continue
		}
		if shell := step['shell'] {
			if shell.string() != 'pwsh' {
				continue
			}
		}
		if condition := step['if'] {
			if condition.string() == '\${{ false }}' {
				continue
			}
		}
		mut environment := map[string]string{}
		if env := step['env'] {
			environment = env.as_map().as_strings()
		}
		steps << Step{
			id:     id
			name:   (step['name'] or { return error('Missing name for ${id}') }).string()
			script: (step['run'] or { return error('Missing command for ${id}') }).string()
			env:    environment
		}
	}
	if steps.len == 0 {
		return error('No validation steps found for ${compiler}')
	}
	return Job{
		compiler: compiler
		env:      job.value('env').as_map().as_strings()
		steps:    steps
	}
}

fn ps_quote(value string) string {
	return "'" + value.replace("'", "''") + "'"
}

fn (job Job) select_steps(id string) ![]Step {
	if id == 'ci' {
		return job.steps
	}
	mut ids := [id]
	if job.compiler == 'msvc' && id == 'multiwindow_d3d11_warp_regressions_and_runtime_probes' {
		// The watchdog is generated by the checkout, rather than installed with MSVC.
		ids.prepend('prepare_multiwindow_job_object_watchdog')
	}
	mut selected := []Step{}
	for step_id in ids {
		matching := job.steps.filter(it.id == step_id)
		if matching.len == 0 {
			return error('Unknown ${job.compiler} step: ${step_id}; use `list` to show available steps')
		}
		selected << matching[0]
	}
	return selected
}

fn step_script(root string, vexe string, environment_file string, path_file string, step Step) string {
	return [
		"\$ErrorActionPreference = 'Stop'",
		"if (\$PSVersionTable.PSVersion -lt [version]'${minimum_powershell_version}') { throw 'Windows CI requires PowerShell ${minimum_powershell_version} or newer' }",
		'\$PSNativeCommandUseErrorActionPreference = \$true',
		'Set-Location -LiteralPath ${ps_quote(root)}',
		// A function also catches `v` after PowerShell's &&, inside loops,
		// and in command substitutions without changing the workflow text.
		'function global:v { & ${ps_quote(vexe)} @args; if (\$LASTEXITCODE -ne 0) { exit \$LASTEXITCODE } }',
		'\$env:PATH = ${ps_quote(root)} + [IO.Path]::PathSeparator + \$env:PATH',
		'\$env:GITHUB_ENV = ${ps_quote(environment_file)}',
		'\$env:GITHUB_PATH = ${ps_quote(path_file)}',
		'\$global:LASTEXITCODE = 0',
		step.script,
		'if (\$LASTEXITCODE -ne 0) { exit \$LASTEXITCODE }',
	].join('\n') + '\n'
}

fn import_environment(environment_file string, path_file string) ! {
	for line in os.read_lines(environment_file)! {
		if line == '' {
			continue
		}
		name, value := line.split_once('=') or {
			return error('Unsupported GITHUB_ENV record: ${line}')
		}
		os.setenv(name, value, true)
	}
	for line in os.read_lines(path_file)! {
		if line != '' {
			os.setenv('PATH', line + os.path_delimiter + os.getenv('PATH'), true)
		}
	}
}

fn execute_step(shell string, root string, vexe string, dir string, step Step) ! {
	mut previous := map[string]?string{}
	for key, value in step.env {
		previous[key] = os.getenv_opt(key)
		os.setenv(key, value, true)
	}
	defer {
		for key, value in previous {
			if saved := value {
				os.setenv(key, saved, true)
			} else {
				os.unsetenv(key)
			}
		}
	}
	environment_file := os.join_path(dir, 'environment')
	path_file := os.join_path(dir, 'path')
	script_file := os.join_path(dir, 'step.ps1')
	os.write_file(environment_file, '')!
	os.write_file(path_file, '')!
	os.write_file(script_file, step_script(root, vexe, environment_file, path_file, step))!
	eprintln('Windows CI: ${step.id} (${step.name})')
	status := os.system_args([shell, '-NoLogo', '-NoProfile', '-NonInteractive', '-ExecutionPolicy',
		'Bypass', '-File', script_file])
	if status != 0 {
		return error('Windows CI step ${step.id} failed (exit ${status})')
	}
	import_environment(environment_file, path_file)!
}

// run executes installed Windows CI validation tasks from the checkout's workflows.
pub fn run(args []string) ! {
	if args.len != 2 {
		return error('Usage: v run ci/windows_ci.vsh <tcc|gcc|msvc> <list|ci|step-id>')
	}
	root := @VEXEROOT
	job := read_job(root, args[0])!
	if args[1] == 'list' {
		for step in job.steps {
			println('${step.id}: ${step.name}')
		}
		return
	}
	selected := job.select_steps(args[1])!
	$if !windows {
		return error('Windows CI execution requires Windows; `list` is available on any host')
	}
	shell := os.find_abs_path_of_executable('pwsh') or {
		return error('Windows CI requires PowerShell ${minimum_powershell_version} or newer (pwsh) on PATH')
	}
	for key, value in job.env {
		// Keep an explicitly chosen worker count for smaller local VMs.
		if key == 'VJOBS' && os.getenv('VJOBS') != '' {
			continue
		}
		os.setenv(key, value, true)
	}
	os.setenv('VTEST_FAIL_FAST', '1', true)
	os.setenv('V_MACOS_V3_NO_FALLBACK', '1', true)
	os.setenv('CI', 'true', true)
	os.setenv('GITHUB_ACTIONS', 'true', true)
	os.setenv('GITHUB_JOB', '${job.compiler}-windows', true)
	os.setenv('RUNNER_OS', 'Windows', true)
	os.setenv('RUNNER_TEMP', os.temp_dir(), true)
	os.unsetenv('VTEST_RESUME_OWNER')
	vexe := os.join_path(root, 'v.exe')
	dir := os.join_path(os.temp_dir(), 'v-windows-ci-${os.getpid()}')
	os.mkdir(dir)!
	defer {
		os.rmdir_all(dir) or {}
	}
	// Reuse the workflow's ACL setup, including its short temporary directory.
	execute_step(shell, root, vexe, dir, Step{
		id:     'prepare_private_tool_cache'
		name:   'Prepare private tool cache'
		script: '. .\\.github\\workflows\\setup_windows_tool_cache.ps1'
	})!
	cache := os.getenv('VTOOLS_CACHE_DIR')
	defer {
		os.rmdir_all(cache) or {}
	}
	for step in selected {
		execute_step(shell, root, vexe, dir, step)!
	}
}
