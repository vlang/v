fn test_libcpp_sort_matches_std_sort() {
	for c in libcpp_sort_cases {
		mut keys := []SortKey{cap: c.keys.len}
		for i, k in c.keys {
			keys << SortKey{
				pipeline_key: k[0]
				uniform_key:  k[1]
				draw:         i
			}
		}
		libcpp_sort(mut keys)
		assert keys.map(it.draw) == c.order, 'n=${c.keys.len}'
	}
}
