module imp

import hash
import os

// Check selects how a flow decides whether it can be skipped.
pub enum Check {
	mtime // skip when every output is newer than every input
	hash  // skip when inputs and set flags match the last successful run
	none  // never skip
}

// AutoFlow names a flow generated from the context targets.
pub enum AutoFlow {
	clean // deletes the targets
	run   // executes the single target
}

// FlowFn is the body of a flow. Returning an error stops the build.
pub type FlowFn = fn (self Flow) !

// FlowDep is a hook on a flow. By default a hook is tied to its flow doing
// work, and is left out when the flow is skipped. A required hook always runs.
// A required pre hook runs ahead of the skip check, and can affect its result.
pub struct FlowDep {
pub:
	id       string @[required]
	required bool
}

// Flag is a boolean `--id` command line switch, declared by the flows reading
// it. It may appear anywhere on the command line, and reaches a declaring flow
// even when that flow only runs as a dependency. A set flag defeats the skip
// check of a declaring flow, as mtimes cannot tell that the flag changes output.
@[params]
pub struct Flag {
pub:
	id   string @[required]
	help string
}

// system_args runs a program with literal arguments and inherited standard
// streams. Unlike `os.system_args`, a failure is an error, so that propagating
// it with `!` fails the flow.
pub fn system_args(args []string) ! {
	code := os.system_args(args)
	if code != 0 {
		name := args[0] or { return error('no program to run') }
		return error(if code < 0 {
			'could not start `${name}`'
		} else {
			'`${name}` exited with status ${code}'
		})
	}
}

// Flow is a unit of work. It is also the parameter struct of `add_flow`.
@[params]
pub struct Flow {
pub:
	id    string @[required]
	name  string // display name, derived from the id when unset
	help  string
	takes []string // input files and directories
	gives []string // output files and directories
	check Check = .mtime
	pre   []FlowDep // hooks run before this flow
	post  []FlowDep // hooks run after this flow
	flags []Flag    // command line switches this flow reads with `flag`
	flow  FlowFn @[required]
mut:
	enabled      []string // the flags set on the command line
	script_flags []string // the ids declared with `Context.flag`
}

// flag reports whether `--id` was given. Reading a flag declared neither by the
// flow nor by `Context.flag` is a mistake in the build script.
pub fn (f Flow) flag(id string) bool {
	if !f.flags.any(it.id == id) && id !in f.script_flags {
		panic('imp: flow `${f.id}` did not declare flag `${id}`')
	}
	return id in f.enabled
}

// display_name returns the name shown to the user.
pub fn (f Flow) display_name() string {
	return if f.name == '' { f.id } else { f.name }
}

// Context holds the targets, flows and flags of a build script.
pub struct Context {
mut:
	targets  []string
	flows    []Flow
	autos    []AutoFlow
	defaults []string
	enabled  []string
	flags    []Flag
}

// new returns an empty build context.
pub fn new() Context {
	return Context{}
}

// add_target registers a build product, for the auto flows to act on.
pub fn (mut c Context) add_target(path string) {
	c.targets << path
}

// add_flow registers a flow. A duplicate id is a mistake in the build script.
pub fn (mut c Context) add_flow(flow Flow) {
	if c.flows.any(it.id == flow.id) {
		panic('imp: duplicate flow id `${flow.id}`')
	}
	c.flows << flow
}

// flag declares a script-level flag and reports whether it was given. It can
// be called before any flow exists, so the answer may shape the build itself,
// like the name of a target. Unlike a flag on a flow, it never defeats a skip.
pub fn (mut c Context) flag(flag Flag) bool {
	c.flags << flag
	return '--${flag.id}' in os.args[1..]
}

// add_auto_flow requests a flow generated from the targets. The flow is
// generated by `flow()`, so targets may be added after this call.
pub fn (mut c Context) add_auto_flow(kind AutoFlow) {
	c.autos << kind
}

// default sets the flows executed when the user names none. It must be called
// before `flow()`, which does not return control to the script on failure.
pub fn (mut c Context) default(ids []string) {
	c.defaults = ids
}

// flow executes the flows named on the command line, or the defaults.
// On failure it reports the error and exits with status 1.
pub fn (mut c Context) flow() {
	c.resolve_auto_flows()
	c.execute(os.args[1..]) or {
		eprintln('imp: ${err.msg()}')
		exit(1)
	}
}

// resolve_auto_flows turns the requested auto flows into ordinary flows.
// A library cannot fail at the script's compile time, because targets are only
// known at runtime. This panics before any flow has executed instead.
fn (mut c Context) resolve_auto_flows() {
	targets := c.targets.clone()
	for kind in c.autos {
		match kind {
			.clean {
				c.add_flow(
					id:    'clean'
					help:  'delete the targets'
					check: .none
					flow:  fn [targets] (_ Flow) ! {
						for target in targets {
							remove(target)!
						}
					}
				)
			}
			.run {
				if targets.len != 1 {
					panic('imp: the run flow needs exactly one target, got ${targets.len}')
				}
				target := targets[0]
				c.add_flow(
					id:    'run'
					help:  'execute the target'
					takes: [target]
					check: .none
					flow:  fn [target] (_ Flow) ! {
						system_args([os.abs_path(target)])!
					}
				)
			}
		}
	}
	c.autos = []
}

// execute parses the command line arguments and runs the flows they name.
fn (mut c Context) execute(args []string) ! {
	if args.len > 0 && args[0] in ['help', '-h', '--help'] && !c.flows.any(it.id == 'help') {
		c.print_help()
		return
	}
	c.enabled = args.filter(it.starts_with('--')).map(it.all_after('--'))
	for id in c.enabled {
		if !c.flags.any(it.id == id) && !c.flows.any(it.flags.any(it.id == id)) {
			return error('unknown flag `--${id}`')
		}
	}
	named := args.filter(!it.starts_with('--'))
	ids := if named.len > 0 { named } else { c.defaults }
	if ids.len == 0 {
		return error('no flow given and no default flow set')
	}
	for id in ids {
		c.find(id)!
	}
	c.validate()!
	for id in ids {
		// each requested flow is its own pass, so `clean run` rechecks build
		mut visited := map[string]bool{}
		c.visit(id, mut visited)!
	}
}

// print_help lists the flows with their flags, then the script-level flags.
fn (c &Context) print_help() {
	width := arrays_max_len(c.flows.map(it.label()))
	println('usage: ${os.file_name(os.args[0])} [flow...]\n')
	for f in c.flows {
		marker := if f.id in c.defaults { ' (default)' } else { '' }
		padding := ' '.repeat(width - f.label().len)
		println('  ${f.label()}${padding}  ${f.help}${marker}'.trim_right(' '))
		for flag in f.flags {
			println('    --${flag.id}  ${flag.help}'.trim_right(' '))
		}
	}
	c.print_script_flags()
}

// label is the help entry of a flow: its display name, plus the id to call it
// by when the two differ.
fn (f Flow) label() string {
	return if f.display_name() == f.id { f.id } else { '${f.display_name()} [${f.id}]' }
}

// arrays_max_len returns the length of the longest string in `items`.
fn arrays_max_len(items []string) int {
	mut max := 0
	for item in items {
		if item.len > max {
			max = item.len
		}
	}
	return max
}

// print_script_flags lists the flags declared with `Context.flag`.
fn (c &Context) print_script_flags() {
	if c.flags.len > 0 {
		println('\nflags:')
	}
	for flag in c.flags {
		println('  --${flag.id}  ${flag.help}'.trim_right(' '))
	}
}

// find returns the flow called `id`, or an error if there is none.
fn (c &Context) find(id string) !Flow {
	for f in c.flows {
		if f.id == id {
			return f
		}
	}
	return error('unknown flow `${id}`')
}

// producers returns the flows whose outputs overlap the inputs of `flow`.
// These are its implicit dependencies.
fn (c &Context) producers(flow Flow) []string {
	mut ids := []string{}
	for other in c.flows {
		if other.id != flow.id && flow.takes.any(overlaps_any(it, other.gives)) {
			ids << other.id
		}
	}
	return ids
}

// overlaps_any reports whether `path` overlaps any of `others`.
fn overlaps_any(path string, others []string) bool {
	return others.any(paths_overlap(path, it))
}

// paths_overlap reports whether the paths are equal or one contains the other.
fn paths_overlap(a string, b string) bool {
	x, y := os.norm_path(a), os.norm_path(b)
	return x == y || x == '.' || y == '.' || x.starts_with(y + os.path_separator)
		|| y.starts_with(x + os.path_separator)
}

// validate rejects unknown hooks and dependency cycles before anything runs.
// Post hooks cannot form a cycle, since they start once their flow is done.
fn (c &Context) validate() ! {
	mut state := map[string]int{} // 1: on the current path, 2: finished
	for f in c.flows {
		for hook in f.post {
			c.find(hook.id)!
		}
		c.check_cycle(f, mut state)!
	}
}

// check_cycle walks what `f` runs ahead of itself, and fails on a cycle.
fn (c &Context) check_cycle(f Flow, mut state map[string]int) ! {
	if state[f.id] == 2 {
		return
	}
	if state[f.id] == 1 {
		return error('dependency cycle through flow `${f.id}`')
	}
	state[f.id] = 1
	for hook in f.pre {
		c.check_cycle(c.find(hook.id)!, mut state)!
	}
	for id in c.producers(f) {
		c.check_cycle(c.find(id)!, mut state)!
	}
	state[f.id] = 2
}

// visit runs a flow and everything it needs, at most once per pass.
fn (c &Context) visit(id string, mut visited map[string]bool) ! {
	if visited[id] {
		return
	}
	visited[id] = true
	f := c.find(id)!
	for hook in f.pre.filter(it.required) {
		c.visit(hook.id, mut visited)!
	}
	for dep in c.producers(f) {
		c.visit(dep, mut visited)!
	}
	// checked here and not earlier: a required pre hook or a dependency may
	// have just removed or rebuilt the outputs
	digest := if f.check == .hash { c.digest(f) } else { '' }
	skip := match f.check {
		.mtime { !f.flags.any(it.id in c.enabled) && is_up_to_date(f) }
		.hash { is_unchanged(f, digest) }
		.none { false }
	}
	if skip {
		println('>> ${f.display_name()} (skip)')
		for hook in f.post.filter(it.required) {
			c.visit(hook.id, mut visited)!
		}
		return
	}
	for hook in f.pre.filter(!it.required) {
		c.visit(hook.id, mut visited)!
	}
	println('>> ${f.display_name()}')
	// dropped first, so that a failed run can never be mistaken for a good one
	os.rm(stamp_path(f)) or {}
	runnable := Flow{
		...f
		enabled:      c.enabled
		script_flags: c.flags.map(it.id)
	}
	f.flow(runnable) or { return error('flow `${f.id}` failed: ${err.msg()}') }
	for path in f.gives {
		if !os.exists(path) {
			return error('flow `${f.id}` did not produce `${path}`')
		}
	}
	if f.check == .hash {
		os.mkdir_all(stamp_dir)!
		os.write_file(stamp_path(f), digest)!
	}
	for hook in f.post {
		c.visit(hook.id, mut visited)!
	}
}

// stamp_dir holds the digests of hash flows, relative to the working directory.
const stamp_dir = '.imp'

// stamp_path is where a hash flow keeps the digest of its last successful run.
fn stamp_path(f Flow) string {
	return os.join_path(stamp_dir, f.id.replace_each(['/', '_', '\\', '_']))
}

// digest identifies the inputs of a flow and the flags that can affect it.
// wyhash is not cryptographic, but it only has to notice changes, and is fast
// enough for inputs of hundreds of megabytes.
fn (c &Context) digest(f Flow) string {
	mut lines := []string{}
	excluded := f.gives.map(os.norm_path(it))
	for path in f.takes {
		hash_path(path, excluded, mut lines)
	}
	lines.sort()
	mut flags := c.enabled.filter(fn [c, f] (id string) bool {
		return f.flags.any(it.id == id) || c.flags.any(it.id == id)
	})
	flags.sort()
	lines << 'flags ${flags.join(' ')}'
	return hash.sum64_string(lines.join('\n'), 0).hex_full()
}

// hash_path appends a line for `path`, and when it is a directory, for every
// file, directory or link under it, to `lines`.
fn hash_path(path string, excluded []string, mut lines []string) {
	if is_real_dir(path) {
		lines << 'dir ${path}'
		for entry in os.ls(path) or { []string{} } {
			child := os.join_path(path, entry)
			if os.norm_path(child) !in excluded {
				hash_path(child, excluded, mut lines)
			}
		}
	} else if bytes := os.read_bytes(path) {
		lines << 'file ${path} ${hash.sum64(bytes, 0).hex_full()}'
	} else {
		// a dangling link, or a link to a directory
		lines << 'other ${path}'
	}
}

// is_unchanged reports whether a hash flow can be skipped. Like mtime flows, it
// needs outputs and all inputs present.
fn is_unchanged(f Flow, digest string) bool {
	if f.gives.len == 0 || f.takes.any(!os.exists(it)) || f.gives.any(!os.exists(it)) {
		return false
	}
	return (os.read_file(stamp_path(f)) or { '' }) == digest
}

// is_up_to_date reports whether an mtime flow can be skipped. It needs outputs
// to compare against, and all inputs present.
//
// Directories count as inputs along with their contents, since creating or
// removing an entry updates the mtime of the directory holding it. An output
// inside an input directory is not an input to itself. mtimes have a resolution
// of one second, so a tie counts as out of date: a needless rebuild beats a
// stale binary.
fn is_up_to_date(f Flow) bool {
	if f.gives.len == 0 || f.takes.any(!os.exists(it)) || f.gives.any(!os.exists(it)) {
		return false
	}
	excluded := f.gives.map(os.norm_path(it))
	mut oldest_output := max_i64
	for path in f.gives {
		oldest_output = min_i64_of(oldest_output, oldest_mtime(path))
	}
	mut newest_input := i64(0)
	for path in f.takes {
		newest_input = max_i64_of(newest_input, newest_mtime(path, excluded))
	}
	return newest_input < oldest_output
}

// max_i64 is the starting point when searching for an oldest mtime.
const max_i64 = i64(9223372036854775807)

// min_i64_of returns the smaller of `a` and `b`.
fn min_i64_of(a i64, b i64) i64 {
	return if a < b { a } else { b }
}

// max_i64_of returns the larger of `a` and `b`.
fn max_i64_of(a i64, b i64) i64 {
	return if a > b { a } else { b }
}

// is_real_dir is false for symlinks, so that walks cannot loop.
fn is_real_dir(path string) bool {
	return os.is_dir(path) && !os.is_link(path)
}

// newest_mtime returns the latest mtime under `path`, leaving out `excluded`.
fn newest_mtime(path string, excluded []string) i64 {
	mut newest := os.file_last_mod_unix(path)
	if is_real_dir(path) {
		for entry in os.ls(path) or { []string{} } {
			child := os.join_path(path, entry)
			if os.norm_path(child) !in excluded {
				newest = max_i64_of(newest, newest_mtime(child, excluded))
			}
		}
	}
	return newest
}

// oldest_mtime returns the earliest mtime under `path`.
fn oldest_mtime(path string) i64 {
	mut oldest := os.file_last_mod_unix(path)
	if is_real_dir(path) {
		for entry in os.ls(path) or { []string{} } {
			oldest = min_i64_of(oldest, oldest_mtime(os.join_path(path, entry)))
		}
	}
	return oldest
}

// remove deletes a file, link or directory. A missing path is not an error.
fn remove(path string) ! {
	if is_real_dir(path) {
		os.rmdir_all(path)!
	} else if os.exists(path) || os.is_link(path) {
		os.rm(path)!
	}
}
