// curated inputs with the results Go gave, so a failure points at the input
// rather than only at a checksum. 'E' marks an input Go rejects; since it
// would decode as an empty string, a success must first be checked against it.
fn test_curated_matches_go() {
	assert curated_hex.len == curated_unquote.len
	assert curated_hex.len == curated_prefix.len
	for i, h in curated_hex {
		s := unhex(h)
		if v := unquote(s) {
			assert curated_unquote[i] != 'E', 'unquote should have failed for ' + h
			assert v == unhex(curated_unquote[i]), 'unquote mismatch for input ' + h
		} else {
			assert curated_unquote[i] == 'E', 'unquote should have failed for ' + h
		}
		if p := quoted_prefix(s) {
			assert curated_prefix[i] != 'E', 'quoted_prefix should have failed for ' + h
			assert p == unhex(curated_prefix[i]), 'quoted_prefix mismatch for input ' + h
		} else {
			assert curated_prefix[i] == 'E', 'quoted_prefix should have failed for ' + h
		}
	}
}

fn hx(s string) string {
	mut out := []u8{}
	for c in s.bytes() {
		out << hexdig(c >> 4)
		out << hexdig(c & 0xF)
	}
	return out.bytestr()
}

fn hexdig(v u8) u8 {
	return if v < 10 { 48 + v } else { 87 + v }
}

fn unhex(s string) string {
	mut out := []u8{}
	mut i := 0
	for i < s.len / 2 {
		mut b := u8(0)
		for j in 0 .. 2 {
			c := s[i * 2 + j]
			d := if c >= `0` && c <= `9` {
				c - `0`
			} else {
				c - `a` + 10
			}
			b = b << 4 | d
		}
		out << b
		i++
	}
	return out.bytestr()
}
