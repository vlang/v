struct Fnv {
mut:
	h u64
}

fn (mut f Fnv) b(v u8) {
	f.h ^= u64(v)
	f.h *= 0x100000001b3
}

fn (mut f Fnv) s(v string) {
	for c in v.bytes() {
		f.b(c)
	}
}

// corpus regenerates the input list. It must produce the same bytes, in the
// same order, as the generator that produced the checksums above; that is what
// corpus_hash verifies.
// one_byte returns a one-byte string. It must build a slice and append,
// because bytestr() on a fixed-size array yields a zeroed string.
fn one_byte(v u8) string {
	mut b := []u8{}
	b << v
	return b.bytestr()
}

fn corpus() []string {
	mut out := []string{len: corpus_count}
	mut n := 0
	dq := one_byte(0x22)
	sq := one_byte(0x27)
	bq := one_byte(0x60)
	for i in 0 .. 256 {
		b := one_byte(u8(i))
		out[n] = dq + b + dq
		n++
		out[n] = sq + b + sq
		n++
		out[n] = bq + b + bq
		n++
	}
	for i in 0 .. 256 {
		a := one_byte(u8(i))
		for j in 0 .. 0x29 {
			b := one_byte(u8(j))
			out[n] = dq + a + b + dq
			n++
			out[n] = sq + a + b + sq
			n++
		}
	}
	return out
}

// test_corpus_is_intact checks the regenerated corpus matches the one the
// checksums were computed over, so a failure elsewhere is a parsing difference
// and not a different input list.
fn test_corpus_is_intact() {
	ins := corpus()
	assert ins.len == corpus_count
	mut f := Fnv{
		h: 0xcbf29ce484222325
	}
	for i, h in ins {
		f.s(i.str() + ':' + hx(h) + ';')
	}
	assert f.h == corpus_hash, 'corpus checksum mismatch'
}

// test_unquote_checksum checks unquote against Go over every corpus input.
fn test_unquote_checksum() {
	mut f := Fnv{
		h: 0xcbf29ce484222325
	}
	for i, s in corpus() {
		if v := unquote(s) {
			f.s(i.str() + ':' + hx(v) + ';')
		} else {
			f.s(i.str() + ':E;')
		}
	}
	assert f.h == unquote_hash, 'unquote checksum mismatch'
}

