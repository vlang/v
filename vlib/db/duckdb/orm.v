module duckdb

import orm
import strconv
import time

struct BindCounter {
mut:
	position int
}

// select is used internally by V's ORM for processing SELECT queries.
pub fn (mut db DB) select(config orm.SelectConfig, data orm.QueryData, where orm.QueryData) ![][]orm.Primitive {
	where_with_tenant := orm.apply_tenant_filter(config.table, where)
	// DuckDB accepts backticks for identifiers, `?N` positional parameters and
	// LIMIT/OFFSET, so the SQLite dialect spelling is reused verbatim.
	query := orm.orm_select_gen(config, '`', true, '?', 1, where_with_tenant)
	$if trace_duckdb ? {
		eprintln('> duckdb.select: ${query}')
	}
	stmt := db.prepare(query)!
	defer {
		stmt.finalize()
	}
	mut c := BindCounter{ position: 1 }
	bind_query_data(&stmt, where_with_tenant, query, mut c)!
	bind_query_data(&stmt, data, query, mut c)!
	rows := stmt.exec(query)!
	mut ret := [][]orm.Primitive{cap: rows.len}
	for row in rows {
		mut vals := []orm.Primitive{cap: config.types.len}
		for i, typ in config.types {
			vals << select_column(row, i, typ)
		}
		ret << vals
	}
	return ret
}

// insert is used internally by V's ORM for processing INSERT queries.
pub fn (mut db DB) insert(table orm.Table, data orm.QueryData) ! {
	query, converted_data := orm.orm_stmt_gen(.sqlite, table, '`', .insert, true, '?', 1, data,
		orm.QueryData{})
	stmt_worker(&db, query, converted_data, orm.QueryData{})!
	db.last_seq = sequence_name(table.name)
}

// update is used internally by V's ORM for processing UPDATE queries.
pub fn (mut db DB) update(table orm.Table, data orm.QueryData, where orm.QueryData) ! {
	where_with_tenant := orm.apply_tenant_filter(table, where)
	query, _ := orm.orm_stmt_gen(.sqlite, table, '`', .update, true, '?', 1, data, where_with_tenant)
	stmt_worker(&db, query, data, where_with_tenant)!
}

// delete is used internally by V's ORM for processing DELETE queries.
pub fn (mut db DB) delete(table orm.Table, where orm.QueryData) ! {
	where_with_tenant := orm.apply_tenant_filter(table, where)
	query, _ := orm.orm_stmt_gen(.sqlite, table, '`', .delete, true, '?', 1, orm.QueryData{},
		where_with_tenant)
	stmt_worker(&db, query, orm.QueryData{}, where_with_tenant)!
}

// last_id returns the value generated by the most recent insert into a table
// with a serial primary key.
//
// DuckDB has no `last_insert_rowid`. This driver creates a sequence named
// `seq_<table>` for every serial primary key (see `create`) and returns its
// current value via `currval()`. It therefore only works for serial primary
// keys created by this module, and returns 0 for other tables. See README.md.
pub fn (mut db DB) last_id() int {
	if db.last_seq == '' {
		return 0
	}
	return db.q_int("SELECT currval('${db.last_seq}')") or { 0 }
}

// duckdb_type_from_v maps V type indices to DuckDB column types.
fn duckdb_type_from_v(typ int) !string {
	// u64 needs UBIGINT: BIGINT would silently truncate values above i64 max.
	if typ == typeof[u64]().idx {
		return 'UBIGINT'
	}
	if typ in orm.nums || typ in orm.num64 || typ in [orm.serial, orm.time_, orm.enum_] {
		return 'BIGINT'
	}
	if typ in orm.float {
		return 'DOUBLE'
	}
	if typ == orm.type_string {
		return 'TEXT'
	}
	return error('duckdb: unsupported V type ${typ}')
}

// create is used internally by V's ORM for table creation (DDL).
pub fn (mut db DB) create(table orm.Table, fields []orm.TableField) ! {
	mut query := orm.orm_table_gen(.sqlite, table, '`', true, 0, fields, duckdb_type_from_v,
		false) or {
		return err
	}
	for field in fields {
		if !is_serial(field) {
			continue
		}
		seq := sequence_name(table.name)
		db.exec('CREATE SEQUENCE IF NOT EXISTS ${seq};')!
		query = inject_default(query, field_sql_name(field), seq)
	}
	for stmt in split_statements(query) {
		db.exec(stmt)!
	}
}

// drop is used internally by V's ORM for table destruction (DDL).
pub fn (mut db DB) drop(table orm.Table) ! {
	db.exec('DROP TABLE IF EXISTS `${table.name}`;')!
}

// execute runs a raw SQL query and returns driver-agnostic ORM rows.
pub fn (mut db DB) execute(query string) ![]orm.Row {
	rows := db.exec(query)!
	mut out := []orm.Row{cap: rows.len}
	for row in rows {
		out << orm.Row{
			vals:  row.vals
			names: row.names
		}
	}
	return out
}

// orm_begin starts a transaction for ORM helpers.
pub fn (mut db DB) orm_begin() ! {
	db.exec('BEGIN TRANSACTION;')!
}

// orm_commit commits the current transaction.
pub fn (mut db DB) orm_commit() ! {
	db.exec('COMMIT;')!
}

// orm_rollback rolls back the current transaction.
pub fn (mut db DB) orm_rollback() ! {
	db.exec('ROLLBACK;')!
}

// orm_savepoint reports that savepoints are unsupported. DuckDB 2.0 does not
// parse SAVEPOINT/ROLLBACK TO/RELEASE, so failing loudly is preferable to
// silently ignoring the request.
pub fn (mut db DB) orm_savepoint(name string) ! {
	return error('duckdb: SAVEPOINT is not supported by DuckDB 2.0 (savepoint: ${name})')
}

// orm_rollback_to reports that savepoints are unsupported (see `orm_savepoint`).
pub fn (mut db DB) orm_rollback_to(name string) ! {
	return error('duckdb: ROLLBACK TO SAVEPOINT is not supported by DuckDB 2.0 (savepoint: ${name})')
}

// orm_release_savepoint reports that savepoints are unsupported (see `orm_savepoint`).
pub fn (mut db DB) orm_release_savepoint(name string) ! {
	return error('duckdb: RELEASE SAVEPOINT is not supported by DuckDB 2.0 (savepoint: ${name})')
}

// begin starts a transaction. A convenience alias for `orm_begin`.
pub fn (mut db DB) begin() ! {
	db.orm_begin()!
}

// commit commits the current transaction. A convenience alias for `orm_commit`.
pub fn (mut db DB) commit() ! {
	db.orm_commit()!
}

// rollback rolls back the current transaction. A convenience alias for `orm_rollback`.
pub fn (mut db DB) rollback() ! {
	db.orm_rollback()!
}

// Helpers

fn stmt_worker(db &DB, query string, data orm.QueryData, where orm.QueryData) ! {
	$if trace_duckdb ? {
		eprintln('> duckdb.stmt_worker: ${query}')
	}
	stmt := db.prepare(query)!
	defer {
		stmt.finalize()
	}
	mut c := BindCounter{ position: 1 }
	bind_query_data(&stmt, data, query, mut c)!
	bind_query_data(&stmt, where, query, mut c)!
	_ = stmt.exec(query)!
}

fn bind_query_data(stmt &Stmt, d orm.QueryData, query string, mut c BindCounter) ! {
	mut kind_index := 0
	for data in d.data {
		for kind_index < d.kinds.len && d.kinds[kind_index] in [.is_null, .is_not_null] {
			kind_index++
		}
		array_operator := kind_index < d.kinds.len && d.kinds[kind_index] in [.in, .not_in]!
		code := bind_value(stmt, mut c, data)
		if code != success {
			return error('duckdb: failed to bind parameter ${c.position} (code ${code}): ${query}')
		}
		if !array_operator {
			c.position++
		}
		kind_index++
	}
}

fn bind_array[T](stmt &Stmt, mut c BindCounter, data []T) int {
	mut err_code := 0
	for element in data {
		tmp := bind_value(stmt, mut c, orm.Primitive(element))
		c.position++
		if tmp != 0 {
			err_code = tmp
			break
		}
	}
	return err_code
}

fn bind_value(stmt &Stmt, mut c BindCounter, data orm.Primitive) int {
	mut err_code := 0
	match data {
		i8, i16, int, u8, u16, u32, bool {
			err_code = stmt.bind_i64(c.position, i64(int(data)))
		}
		i64 {
			err_code = stmt.bind_i64(c.position, i64(data))
		}
		u64 {
			err_code = stmt.bind_u64(c.position, u64(data))
		}
		f32, f64 {
			err_code = stmt.bind_f64(c.position, f64(data))
		}
		string {
			err_code = stmt.bind_text(c.position, data)
		}
		time.Time {
			err_code = stmt.bind_i64(c.position, data.unix())
		}
		orm.InfixType {
			err_code = bind_value(stmt, mut c, data.right)
		}
		orm.Null {
			err_code = stmt.bind_null(c.position)
		}
		[]orm.Primitive {
			err_code = bind_array(stmt, mut c, data)
		}
		[]bool {
			err_code = bind_array(stmt, mut c, data)
		}
		[]f32 {
			err_code = bind_array(stmt, mut c, data)
		}
		[]f64 {
			err_code = bind_array(stmt, mut c, data)
		}
		[]i16 {
			err_code = bind_array(stmt, mut c, data)
		}
		[]i64 {
			err_code = bind_array(stmt, mut c, data)
		}
		[]i8 {
			err_code = bind_array(stmt, mut c, data)
		}
		[]int {
			err_code = bind_array(stmt, mut c, data)
		}
		[]string {
			err_code = bind_array(stmt, mut c, data)
		}
		[]time.Time {
			err_code = bind_array(stmt, mut c, data)
		}
		[]u16 {
			err_code = bind_array(stmt, mut c, data)
		}
		[]u32 {
			err_code = bind_array(stmt, mut c, data)
		}
		[]u64 {
			err_code = bind_array(stmt, mut c, data)
		}
		[]u8 {
			err_code = bind_array(stmt, mut c, data)
		}
		[]orm.InfixType {
			err_code = bind_array(stmt, mut c, data)
		}
	}
	return err_code
}

fn select_column(row Row, idx int, typ int) orm.Primitive {
	if idx >= row.vals.len || row.is_null(idx) {
		return orm.Null{}
	}
	val := row.vals[idx]
	if typ in orm.nums || typ == -1 {
		return val.int()
	}
	if typ == typeof[u64]().idx {
		// UBIGINT values above i64 max must not be read back as wrapped i64.
		return strconv.parse_uint(val, 10, 64) or { return orm.Null{} }
	}
	if typ in orm.num64 {
		return val.i64()
	}
	if typ == typeof[f32]().idx {
		return f32(val.f64())
	}
	if typ == typeof[f64]().idx {
		return val.f64()
	}
	if typ == orm.type_string {
		return val.clone()
	}
	if typ == orm.enum_ {
		// V stores enums as integers, but externally created tables may keep the
		// textual label. Pass labels through and convert numeric values to i64.
		n := strconv.parse_int(val, 10, 64) or { return val.clone() }
		return i64(n)
	}
	if typ == orm.time_ {
		n := strconv.parse_int(val, 10, 64) or { return orm.Null{} }
		return time.unix(n)
	}
	return orm.Null{}
}

fn sequence_name(table string) string {
	return 'seq_${table}'
}

fn is_serial(field orm.TableField) bool {
	if field.typ == orm.serial {
		return true
	}
	for attr in field.attrs {
		if attr.name == 'serial' && attr.kind == .plain && !attr.has_arg {
			return true
		}
		if attr.name == 'sql' && attr.has_arg && attr.arg.to_lower() == 'serial' {
			return true
		}
	}
	return false
}

fn field_sql_name(field orm.TableField) string {
	for attr in field.attrs {
		if attr.name == 'sql' && attr.has_arg && attr.kind == .string {
			out := attr.arg.trim_space()
			if out.len >= 2 && ((out.starts_with("'") && out.ends_with("'"))
				|| (out.starts_with('"') && out.ends_with('"'))) {
				return out[1..out.len - 1].trim_space()
			}
			return out
		}
	}
	return field.name
}

// inject_default adds `DEFAULT nextval('<seq>')` to a serial column definition
// produced by orm.orm_table_gen.
fn inject_default(query string, col string, seq string) string {
	needle := '`${col}` '
	idx := query.index(needle) or { return query }
	start := idx + needle.len
	mut end := start
	for end < query.len {
		ch := query[end]
		if ch == u8(32) || ch == u8(44) || ch == u8(10) || ch == u8(41) {
			break
		}
		end++
	}
	return query[..end] + " DEFAULT nextval('${seq}')" + query[end..]
}

// split_statements splits generated DDL, which may contain several semicolon
// separated statements (CREATE TABLE followed by CREATE INDEX), so that each
// is sent to duckdb_query on its own.
fn split_statements(query string) []string {
	mut out := []string{}
	for part in query.split(';') {
		s := part.trim_space()
		if s != '' {
			out << s + ';'
		}
	}
	return out
}
