module capi

import os
import strings

pub struct EmitOptions {
pub:
	out_dir     string
	lib_name    string
	version     string
	description string
}

pub struct EmitResult {
pub:
	header string
	def    string
	pc     string
	demo   string
	readme string
}

// emit_files writes the release artifacts into out_dir and returns their
// paths. The header is the single source of truth for C consumers and is
// generated from the same export list used to build the library.
pub fn emit_files(m ApiModel, infos []ExportInfo, opts EmitOptions) !EmitResult {
	os.mkdir_all(opts.out_dir) or { return error('cannot create ${opts.out_dir}: ${err}') }
	name := if opts.lib_name == '' { m.prefix } else { sanitize(opts.lib_name) }
	version := if opts.version == '' { '0.1.0' } else { opts.version }
	description := if opts.description == '' {
		'C library generated from the V module ${m.module_name}'
	} else {
		opts.description
	}
	all := with_runtime(m, infos)
	guard := sanitize(name).to_upper()
	h := header_text(m, name, version, all)
	d := def_text(name, all)
	p := pc_text(name, description, version)
	demo := demo_text(m, name, all)
	readme := readme_text(m, name, version, all)
	header_path := os.join_path(opts.out_dir, '${name}.h')
	def_path := os.join_path(opts.out_dir, '${name}.def')
	pc_path := os.join_path(opts.out_dir, '${name}.pc')
	demo_path := os.join_path(opts.out_dir, 'demo.c')
	readme_path := os.join_path(opts.out_dir, 'README.md')
	os.write_file(header_path, h) or { return error('cannot write ${header_path}: ${err}') }
	os.write_file(def_path, d) or { return error('cannot write ${def_path}: ${err}') }
	os.write_file(pc_path, p) or { return error('cannot write ${pc_path}: ${err}') }
	os.write_file(demo_path, demo) or { return error('cannot write ${demo_path}: ${err}') }
	os.write_file(readme_path, readme) or { return error('cannot write ${readme_path}: ${err}') }
	_ = guard
	return EmitResult{
		header: header_path
		def:    def_path
		pc:     pc_path
		demo:   demo_path
		readme: readme_path
	}
}

fn with_runtime(m ApiModel, infos []ExportInfo) []ExportInfo {
	mut all := [
		ExportInfo{
			c_name:    '${m.prefix}_init'
			signature: 'int ${m.prefix}_init(void)'
			doc:       'Initialises the V runtime. Call once before other functions.'
		},
		ExportInfo{
			c_name:    '${m.prefix}_last_error'
			signature: 'const char *${m.prefix}_last_error(void)'
			doc:       'Returns the last error message on this thread, never NULL.'
		},
		ExportInfo{
			c_name:    '${m.prefix}_free'
			signature: 'void ${m.prefix}_free(void *p)'
			doc:       'Frees a string or buffer returned by this library.'
		},
	]
	all << infos
	return all
}

fn header_text(m ApiModel, name string, version string, all []ExportInfo) string {
	mut b := strings.Builder{}
	guard := sanitize(name).to_upper() + '_H'
	b.writeln('// ${name}.h — generated by `v c-api` from V module ${m.module_name}.')
	b.writeln('// Do not edit by hand; regenerate with `v c-api`.')
	b.writeln('#ifndef ${guard}')
	b.writeln('#define ${guard}')
	b.writeln('')
	b.writeln('#ifdef __cplusplus')
	b.writeln('extern "C" {')
	b.writeln('#endif')
	b.writeln('')
	b.writeln('#include <stddef.h>')
	b.writeln('#include <stdint.h>')
	b.writeln('#include <stdbool.h>')
	b.writeln('')
	b.writeln('#define ${sanitize(name).to_upper()}_VERSION "${version}"')
	for t in m.types {
		if t.kind != 'struct' {
			continue
		}
		cname := if t.c_name != '' { t.c_name } else { '${m.prefix}_${sanitize(t.name)}' }
		if is_plain_struct(m, t.name) {
			b.writeln('typedef struct ${cname} {')
			for f in t.fields {
				b.writeln('\t${struct_field_c_type(f.type_name) or { continue }} ${f.name};')
			}
			b.writeln('} ${cname};')
		} else {
			b.writeln('typedef struct ${cname} ${cname};')
		}
	}
	for t in m.types {
		if t.kind == 'enum' {
			cname := if t.c_name != '' { t.c_name } else { '${m.prefix}_${sanitize(t.name)}' }
			b.writeln('typedef enum ${cname} {')
			for i, member in t.members {
				b.writeln('\t${cname}_${member} = ${i},')
			}
			b.writeln('} ${cname};')
		}
	}
	b.writeln('')
	for info in all {
		for line in info.doc.split('\n') {
			if line.trim_space() != '' {
				b.writeln('// ${line}')
			}
		}
		b.writeln('${info.signature};')
		b.writeln('')
	}
	b.writeln('#ifdef __cplusplus')
	b.writeln('}')
	b.writeln('#endif')
	b.writeln('')
	b.writeln('#endif // ${guard}')
	return b.str()
}

fn def_text(name string, all []ExportInfo) string {
	mut b := strings.Builder{}
	b.writeln('; ${name}.def — generated by `v c-api`.')
	b.writeln('LIBRARY ${name}')
	b.writeln('EXPORTS')
	for info in all {
		b.writeln('\t${info.c_name}')
	}
	return b.str()
}

fn pc_text(name string, description string, version string) string {
	mut b := strings.Builder{}
	mut dollar := '$'
	b.writeln('prefix=/usr/local')
	b.writeln('exec_prefix=' + dollar + '{prefix}')
	b.writeln('libdir=' + dollar + '{exec_prefix}/lib')
	b.writeln('includedir=' + dollar + '{prefix}/include')
	b.writeln('')
	b.writeln('Name: ${name}')
	b.writeln('Description: ${description}')
	b.writeln('Version: ${version}')
	b.writeln('Libs: -L' + dollar + '{libdir} -l${name}')
	b.writeln('Cflags: -I' + dollar + '{includedir}')
	return b.str()
}

fn demo_text(m ApiModel, name string, all []ExportInfo) string {
	mut b := strings.Builder{}
	b.writeln('// demo.c — generated by `v c-api`. A minimal link check.')
	b.writeln('#include <stdio.h>')
	b.writeln('#include "${name}.h"')
	b.writeln('')
	b.writeln('int main(void) {')
	b.writeln('\t${m.prefix}_init();')
	b.writeln('\tprintf("${name} %s\\n", ${sanitize(name).to_upper()}_VERSION);')
	if all.len > 3 {
		first := all[3]
		b.writeln('\t/* Example export: ${first.signature}; */')
	}
	b.writeln('\tprintf("last error: %s\\n", ${m.prefix}_last_error());')
	b.writeln('\treturn 0;')
	b.writeln('}')
	return b.str()
}

fn readme_text(m ApiModel, name string, version string, all []ExportInfo) string {
	mut b := strings.Builder{}
	b.writeln('# ${name} (C API)')
	b.writeln('')
	b.writeln('Generated from the V module `${m.module_name}` by `v c-api`.')
	b.writeln('Version: ${version}.')
	b.writeln('')
	b.writeln('## Files')
	b.writeln('')
	b.writeln('- `${name}.h` — C declarations (include this).')
	b.writeln('- `${name}.def` — Windows DLL export list.')
	b.writeln('- `${name}.pc` — pkg-config metadata.')
	b.writeln('- `demo.c` — minimal link check.')
	b.writeln('- shared library: `lib${name}.so`, `${name}.dll`, or `lib${name}.dylib`.')
	b.writeln('- Windows import libraries: `lib${name}.dll.a` (MinGW) and `${name}.lib` (MSVC),')
	b.writeln('  generated when `dlltool` / `lib` are available; otherwise build them from the `.def`.')
	b.writeln('')
	b.writeln('## Build')
	b.writeln('')
	b.writeln('```sh')
	b.writeln('v c-api <module-dir> -o dist --lib-name ${name}')
	b.writeln('cc -o demo demo.c -I. -L. -l${name}')
	b.writeln('# Windows alternative: link the import library by path')
	b.writeln('cc -o demo.exe demo.c -I. lib${name}.dll.a')
	b.writeln('```')
	b.writeln('')
	b.writeln('## Exported functions (${all.len})')
	b.writeln('')
	for info in all {
		b.writeln('- `${info.signature};`')
	}
	b.writeln('')
	b.writeln('Returned strings and buffers are owned by the caller; release them with')
	b.writeln('`${m.prefix}_free()`. `!T` results return 0 on success and -1 on error,')
	b.writeln('with the message available from `${m.prefix}_last_error()`; `?T` results')
	b.writeln('return 0 for a value and 1 for none.')
	return b.str()
}
