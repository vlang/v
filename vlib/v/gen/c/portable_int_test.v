const portable_int_program = 'fn add(a int, b int) int {
	return a + b
}

fn pair(n int) (int, i64) {
	return n * 2, i64(n) * 3
}

fn maybe(n int) ?int {
	if n < 0 {
		return none
	}
	return n
}

fn main() {
	assert sizeof(uint) == sizeof(int)
	assert sizeof(uint) == sizeof(voidptr)
	maximum := ~uint(0)
	assert maximum >> (sizeof(uint) * 8 - 1) == 1
	assert maximum + uint(1) == 0
	mut unsigned_keys := map[uint]int{}
	unsigned_keys[maximum] = 17
	assert unsigned_keys[maximum] == 17
	mut m := map[int]string{}
	for i in 0 .. 100 {
		m[i * 7] = i.str()
	}
	println(m[49])
	println(m.len)
	shift := 3
	println(1 << shift)
	println(-64 >> shift)
	fixed := [3]int{init: index * 5}
	println(fixed[2])
	a, b := pair(21)
	println(a)
	println(b)
	println(maybe(9) or { -1 })
	println(min_int < 0 && max_int > 0)
	println(int(max_i32) <= max_int)
	k := 40
	f := fn [k] (x int) int {
		return add(x, k)
	}
	println(f(2))
}
'

const portable_int_program_output = '7\n100\n8\n-8\n10\n42\n63\n9\ntrue\ntrue\n42\n'

fn test_portable_int_helpers_follow_the_c_target() {
	unsigned_type, bits := unsigned_shift_parts(types.portable_int_c_type)
	assert unsigned_type == portable_uint_c_type
	assert bits == '__V_INT_BITS'
	// A constant shift below 32 is valid at either width.
	assert fixed_integer_c_type_width(types.portable_int_c_type) or { 0 } == 32
	assert map_key_has_pointer_width(types.Type(types.int_), types.portable_int_c_type)
	assert !map_key_has_pointer_width(types.Type(types.i64_), 'i64')
	mut g := FlatGen.new()
	g.set_target(pref.target_from('linux', 'amd64')!)
	g.set_output_cross_c(true)
	g.undef_target_identifier_macros()
	// TinyCC predefines `arm` and `arm_elf` only on 32-bit ARM.
	assert g.sb.str() == '#if defined(__arm__)\n#undef arm\n#undef arm_elf\n#endif\n'
}

// Portable C (`-os cross`) spells `int` as `__v_int`, which it defines from the width
// of the C compiler's target, so the same file has to be valid for 64-bit and
// 32-bit targets and agree on `int` everywhere. With V's own libc declarations it
// needs no sysroot to check.
fn test_cross_output_defines_int_from_the_c_target() {
	$if !(macos || linux) || freestanding {
		return
	}
	root := os.join_path(os.vtmp_dir(), 'portable_int_${os.getpid()}')
	os.mkdir_all(root)!
	defer { os.rmdir_all(root) or {} }
	source := os.join_path(root, 'main.v')
	c_file := os.join_path(root, 'main.c')
	os.write_file(source, portable_int_program)!
	generated := cmdexec.run(@VEXE, ['-nocache', '-os', 'linux', '-cross', '-d',
		'v3_headerless_bootstrap', '-o', c_file, source])
	assert generated.exit_code == 0, generated.output
	code := os.read_file(c_file)!
	assert code.contains('#if __V_INT_BITS == 64\ntypedef i64 __v_int;\n'), code[..2000]
	assert code.contains('#else\ntypedef i32 __v_int;\n'), code[..2000]
	assert !code.contains('#error "this C was generated by')
	// The callbacks of maps with `int` keys, the limits of `int` and the closure
	// thunk are selected for the C compiler's target too.
	assert code.contains('map_hash_int_w'), 'int-keyed maps use the pointer-width callbacks'
	assert code.contains('#define map_hash_int_w map_hash_int_4')
	assert code.contains('portable_max_int()'), 'max_int follows the C target'
	assert code.contains('closure__portable_closure_thunk()'), 'the closure thunk follows the C target'
	assert code.contains('Array_fixed___v_int_3'), 'derived names spell int the same for every width'
	if clang := os.find_abs_path_of_executable('clang') {
		for target in ['x86_64-unknown-linux-gnu', 'aarch64-unknown-linux-gnu',
			'armv7-unknown-linux-gnueabihf', 'i686-unknown-linux-gnu'] {
			checked := os.exec([clang, '-target', target, '-std=c99', '-fsyntax-only', '-Wno-everything',
				'-Werror=implicit-function-declaration', '-Werror=incompatible-pointer-types',
				'-Wno-error=incompatible-pointer-types-discards-qualifiers', '-Werror=int-conversion',
				c_file])
			assert checked.exit_code == 0, '${target}: ${checked.output}'
		}
	}
	// The ordinary output is unchanged.
	native := cmdexec.run(@VEXE, ['-nocache', '-o', c_file, source])
	assert native.exit_code == 0, native.output
	assert !os.read_file(c_file)!.contains('__v_int')
}

fn test_cross_output_runs_on_the_host() {
	$if !(macos || linux) || freestanding {
		return
	}
	cc := os.find_abs_path_of_executable('cc') or { return }
	root := os.join_path(os.vtmp_dir(), 'portable_int_run_${os.getpid()}')
	os.mkdir_all(root)!
	defer { os.rmdir_all(root) or {} }
	source := os.join_path(root, 'main.v')
	c_file := os.join_path(root, 'main.c')
	exe := os.join_path(root, 'main')
	os.write_file(source, portable_int_program)!
	generated := cmdexec.run(@VEXE, ['-nocache', '-gc', 'none', '-cross', '-o', c_file, source])
	assert generated.exit_code == 0, generated.output
	compiled := os.exec([cc, '-std=gnu11', '-w', '-o', exe, c_file, '-lm', '-lpthread'])
	assert compiled.exit_code == 0, compiled.output
	run := os.exec([exe])
	assert run.exit_code == 0, run.output
	assert run.output == portable_int_program_output
}
