import os
import v.cmdexec

// os.exec runs an absolute path as written, without adding `.exe`.
const soa_parallel_exe_suffix = $if windows { '.exe' } $else { '' }

const soa_parallel_source = "@[soa]
struct Particle {
	id   int
	name string
}

@[typedef]
struct C.Particle_SOA {
	len  int
	cap  int
	id   &int
	name &string
}

fn C.Particle_SOA_new(int, int) C.Particle_SOA
fn C.Particle_SOA_push(&C.Particle_SOA, Particle)
fn C.Particle_SOA_get(C.Particle_SOA, int) Particle
fn C.Particle_SOA_free(&C.Particle_SOA)

fn main() {
	mut soa := C.Particle_SOA_new(0, 2)
	for i in 0 .. 5 {
		C.Particle_SOA_push(&soa, Particle{id: i * 10, name: 'p' + i.str()})
	}
	last := C.Particle_SOA_get(soa, 4)
	println(soa.len.str() + ':' + soa.cap.str() + ':' + last.id.str() + ':' + last.name)
	C.Particle_SOA_free(&soa)
	println(soa.len.str() + ':' + soa.cap.str())
}
"

// With three or more jobs, the type declaration block (which holds the SoA
// companion typedef and its `_new/_get/_set/_push/_pop/_free` definitions) is
// generated by a parallel task on a forked checker. That fork must see the
// `@[soa]` structs, or the companion is dropped and only the prototypes of the
// `fn C.` declarations remain. The C must not depend on the job count.
fn test_soa_companion_is_generated_once_for_every_job_count() {
	test_dir := os.join_path(os.vtmp_dir(), 'soa_companion_parallel_cgen_${os.getpid()}')
	os.mkdir_all(test_dir) or { panic(err) }
	defer {
		os.rmdir_all(test_dir) or {}
	}
	v_file := os.join_path(test_dir, 'main.v')
	os.write_file(v_file, soa_parallel_source) or { panic(err) }
	mut serial_code := ''
	for jobs in ['1', '2', '4', '8'] {
		c_file := os.join_path(test_dir, 'main_${jobs}.c')
		generated := cmdexec.run_in_merged_with_env(@VEXE, ['-nocache', '-o', c_file, v_file],
			test_dir, {
				'VJOBS': jobs
			})
		assert generated.exit_code == 0, 'VJOBS=${jobs}: ${generated.output}'
		code := os.read_file(c_file) or { panic(err) }
		assert code.count('typedef struct Particle_SOA {') == 1, 'VJOBS=${jobs}'
		for definition in ['Particle_SOA Particle_SOA_new(int len, int cap) {',
			'main__Particle Particle_SOA_get(Particle_SOA soa, int i) {',
			'void Particle_SOA_push(Particle_SOA* soa, main__Particle val) {',
			'void Particle_SOA_free(Particle_SOA* soa) {'] {
			assert code.count(definition) == 1, 'VJOBS=${jobs}: ${definition}'
		}
		if jobs == '1' {
			serial_code = code
		} else {
			assert code == serial_code, 'VJOBS=${jobs}: the C differs from VJOBS=1'
		}
	}
	exe := os.join_path(test_dir, 'soa_program${soa_parallel_exe_suffix}')
	built := cmdexec.run_in_merged_with_env(@VEXE, ['-nocache', '-o', exe, v_file], test_dir, {
		'VJOBS': '4'
	})
	assert built.exit_code == 0, built.output
	ran := os.exec([exe])
	assert ran.exit_code == 0, ran.output
	assert ran.output.trim_space().split_into_lines() == ['5:8:40:p4', '0:0']
}
