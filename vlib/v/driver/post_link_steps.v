module driver

import v.cmdexec

// Everything the driver does to the output after the C compiler has linked it is shown with
// `-showcc` and `-v`, with the `  > ` prefix of the compiler's own command line. The step
// texts are plain functions, so that the Windows and macOS ones can be checked on any host.

// post_link_step_line formats `step` the way the compiler command lines are shown.
fn post_link_step_line(step string) string {
	return '  > ${step}'
}

// print_post_link_step prints the line of `step` when `trace` (`-showcc` or `-v`) is on.
fn print_post_link_step(trace bool, step string) {
	if trace {
		println(post_link_step_line(step))
	}
}

// post_link_move_step describes the move of the linked file into its final place, which
// every build on every OS ends with.
fn post_link_move_step(staged_binary string, bin_file string) string {
	return cmdexec.display('mv', [staged_binary, bin_file])
}

// macos_codesign_step describes the `codesign` call that gives a macOS executable its
// ad-hoc signature.
fn macos_codesign_step(output string) string {
	return cmdexec.display('codesign', ['-f', '-s', '-', output])
}

// macos_in_process_codesign_step describes the signing that the driver does itself, in
// place of the `codesign` call above.
fn macos_in_process_codesign_step(output string) string {
	return 'ad-hoc sign ${output} (in process, same as ${macos_codesign_step(output)})'
}

// macos_dsym_step describes the creation of the `.dSYM` bundle of a macOS debug binary.
fn macos_dsym_step(dsymutil string, bin_file string, target_dsym string) string {
	return cmdexec.display(dsymutil, [bin_file, '-o', target_dsym])
}

// macos_dsym_move_step describes the move of the `.dSYM` bundle that the C compiler wrote
// beside the staged binary.
fn macos_dsym_move_step(staged_dsym string, target_dsym string) string {
	return cmdexec.display('mv', [staged_dsym, target_dsym])
}

// windows_manifest_step describes what the driver does to the `.manifest` file beside a
// Windows executable: write the longPathAware sidecar, or remove one it generated earlier.
fn windows_manifest_step(exe_path string, remove bool) string {
	return if remove {
		'rm ${exe_path}.manifest (generated by an earlier build, not wanted with MSVC)'
	} else {
		'write ${exe_path}.manifest (longPathAware, the executable has no manifest)'
	}
}
