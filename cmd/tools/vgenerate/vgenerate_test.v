}

fn test_generate_model_never_overwrites() {
	old_wd := gen_setup()
	defer {
		gen_teardown(old_wd)
	}
	os.mkdir_all('models') or { panic(err) }
	os.write_file(os.join_path('models', 'user.v'), 'hand-written') or { panic(err) }
	generate_model(['User', 'name:string']) or {
		assert err.msg().contains('already exists'), 'wrong error: ${err.msg()}'
		return
	}
	assert false, 'an existing file must be refused'
	assert os.read_file(os.join_path('models', 'user.v')) or { '' } == 'hand-written'
}

fn test_generate_model_rejects_reserved_id_field() {
	old_wd := gen_setup()
	defer {
		gen_teardown(old_wd)
	}
	generate_model(['User', 'id:string']) or {
		assert err.msg().contains('duplicate field name'), 'wrong error: ${err.msg()}'
		assert !os.exists(os.join_path('models', 'user.v')), 'no file must be written on error'
		return
	}
	assert false, 'the reserved autogenerated `id` must be rejected'
}

fn test_generate_model_rejects_duplicate_field_names() {
	old_wd := gen_setup()
	defer {
		gen_teardown(old_wd)
	}
	generate_model(['User', 'name:string', 'name:int']) or {
		assert err.msg().contains('duplicate field name'), 'wrong error: ${err.msg()}'
		assert !os.exists(os.join_path('models', 'user.v')), 'no file must be written on error'
		return
	}
	assert false, 'repeated field names must be rejected'
}

fn test_generate_model_rejects_invalid_field_names() {
	for spec in [':string', 'first-name:string', '1name:string'] {
		old_wd := gen_setup()
		generate_model(['User', spec]) or {
			assert err.msg().contains('invalid field name'), 'wrong error for `${spec}`: ${err.msg()}'
			assert !os.exists(os.join_path('models', 'user.v')), 'no file must be written for `${spec}`'
			gen_teardown(old_wd)
			continue
		}
		gen_teardown(old_wd)
		assert false, 'invalid field `${spec}` must be rejected'
	}
}

fn test_generate_controller_writes_a_veb_controller_stub() {
	old_wd := gen_setup()
	defer {
		gen_teardown(old_wd)
	}
	generate_controller(['Users']) or {
		assert false, 'generate_controller failed: ${err}'
		return
	}
	content := os.read_file('users_controller.v') or {
		assert false, 'users_controller.v was not created'
		return
	}
	assert content.contains('pub struct UsersController {')
	assert content.contains('veb.Controller')
	assert content.contains("@['/'; get]")
	assert content.contains("@['/:id'; get]")
	assert content.contains("register_controller[UsersController, Context]('/users'")
}

fn test_snake_case_converts_camel_names() {
	assert snake_case('User') == 'user'
	assert snake_case('UserProfile') == 'user_profile'
	assert snake_case('API') == 'a_p_i'
}
