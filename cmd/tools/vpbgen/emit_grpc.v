module main

// emit_grpc writes a standalone file holding only the service declarations.
//
// A separate output file works because V treats two files in one directory that
// declare the same module as one module, so the service half sees the message
// types the codec half declares without an import. When the two halves share a
// file instead, use emit_grpc_body: a second `module` line in one file is a
// syntax error.
pub fn emit_grpc(res &ResolvedFile) string {
	mut e := new_emitter()
	e.w('// Code generated by `v pbgen`. DO NOT EDIT.')
	e.w('//')
	e.w('// The service paths and interfaces below. The handler bodies are the')
	e.w("// caller's: `net.grpc` moves payloads as []u8 and never looks inside them, so")
	e.w('// only the codec needs to know the message types.')
	e.w('')
	e.w('module ${res.module}')
	e.w('')
	e.w(emit_grpc_body(res))
	return e.result()
}

// emit_grpc_body returns just the service declarations, with no header, module
// line, or imports, so it can be appended to the codec output.
pub fn emit_grpc_body(res &ResolvedFile) string {
	mut e := new_emitter()
	for svc in res.services {
		emit_service(mut e, res, svc)
	}
	return e.result()
}

// emit_service writes one service's paths and interface.
pub fn emit_service(mut e Emitter, res &ResolvedFile, svc Service) {
	qualified := if res.package == '' {
		svc.name
	} else {
		'${res.package}.${svc.name}'
	}
	v_name := safe_type_name(svc.name)
	prefix := snake_case(svc.name)
	emit_comment(mut e, 0, svc.comments)
	e.wln(0, '// ${prefix}_service_path is the fully qualified service name a gRPC client')
	e.wln(0, '// addresses this service by. It is a path, not a network address.')
	e.wln(0, "pub const ${prefix}_service_path = '/${qualified}'")
	for r in svc.rpcs {
		e.wln(0, '// ${prefix}_method_${snake_case(r.name)} is the path of the `${r.name}`')
		e.wln(0, '// method. A gRPC request line is this path, so a client and a server')
		e.wln(0, '// agree on it before any message is exchanged.')
		e.wln(0, "pub const ${prefix}_method_${snake_case(r.name)} = '/${qualified}/${r.name}'")
	}
	e.wln(0, '// ${v_name} is the handler interface for the gRPC service `${qualified}`.')
	e.wln(0, '//')
	e.wln(0, '// A method returns a `grpc.StatusError` as its error to fail the call with a')
	e.wln(0, '// typed code; a transport error is something else entirely, and the client')
	e.wln(0, '// can only tell the two apart if they stay distinct.')
	e.wln(0, '//')
	e.wln(0, '// The signatures are transport-free on purpose: no `net.grpc` type appears, so')
	e.wln(0, '// this file compiles without the transport module and the adapter that')
	e.wln(0, "// registers a service is the caller's to write.")
	e.wln(0, 'pub interface ${v_name} {')
	for r in svc.rpcs {
		emit_comment(mut e, 1, r.comments)
		e.wln(1, '// ${r.name} is `${r.request_type}` -> `${r.response_type}`${streaming_note(r)}.')
		e.wln(1, rpc_signature(r))
	}
	e.wln(0, '}')
	e.w('')
}

// streaming_note describes an rpc's streaming shape, for the doc comment above
// its signature.
pub fn streaming_note(r Rpc) string {
	return if r.client_stream && r.server_stream {
		' (bidirectional streaming)'
	} else if r.client_stream {
		' (client streaming)'
	} else if r.server_stream {
		' (server streaming)'
	} else {
		''
	}
}

// rpc_signature returns the V signature for one rpc.
//
// The request and response sides follow the streaming flags independently,
// which is what makes a streaming signature meaningful: a server-streamed rpc
// takes one request and returns many responses, and a client-streamed one takes
// many requests and returns a single response. Giving every flavour the unary
// signature would have made a server-streamed handler declare it returns one
// message and then have nowhere to put the rest.
pub fn rpc_signature(r Rpc) string {
	name := method_fn_name(r)
	req := if r.client_stream {
		'reqs []${r.request_v_type}'
	} else {
		'req ${r.request_v_type}'
	}
	resp := if r.server_stream {
		'![]${r.response_v_type}'
	} else {
		'!${r.response_v_type}'
	}
	return '${name}(${req}) ${resp}'
}

// method_fn_name returns the V method name for an rpc, which keeps the schema's
// capitalisation off a V method name that would otherwise read oddly.
pub fn method_fn_name(r Rpc) string {
	name := snake_case(r.name)
	if name == '' {
		return 'call'
	}
	if is_v_keyword(name) {
		return '${name}_'
	}
	return name
}

// service_method_table writes a table a dispatcher can match on, which is what a
// handler that serves several services needs.
//
// It is emitted as a set of `match` arms rather than a map, so adding a method to
// the schema produces a compile error in every dispatcher that forgot it, which a
// map would not.
pub fn emit_service_dispatch_table(mut e Emitter, res &ResolvedFile, svc Service) {
	prefix := snake_case(svc.name)
	for r in svc.rpcs {
		e.wln(1, '${prefix}_method_${snake_case(r.name)} {')
		e.wln(2, '// ${r.name}: ${r.request_type} -> ${r.response_type}')
		e.wln(1, '}')
	}
	_ = res
	_ = svc
	_ = e
}

// grpc_status_error_note is the one sentence worth repeating in the generated
// header, since getting it wrong is the most common way a gRPC handler in V
// reports a business error as a transport failure.
pub const grpc_status_error_note = 'A handler fails a call with a grpc.StatusError as its *error*, not as a payload.'
