fn test_zero_value_is_a_usable_mut_initializer() {
	// `i32{}` does not compile: V reads it as a composite literal for an unknown
	// type. Every generated `mut` local has to be initialised this way instead.
	assert zero_value('i32') == 'i32(0)'
	assert zero_value('u64') == 'u64(0)'
	assert zero_value('f64') == 'f64(0)'
	assert zero_value('bool') == 'false'
	assert zero_value('string') == "''"
	// A composite type keeps its literal, which is the only form that works for
	// a map or a list.
	assert zero_value('map[string]i32') == 'map[string]i32{}'
	assert zero_value('GetRequest') == 'GetRequest{}'
}

