fn test_generated_grpc_paths_and_interface() {
	out := generate_grpc(fixture('kv.proto'), 'kv')!
	// The path is what a client and a server agree on before any message moves.
	assert out.contains("pub const kv_service_path = '/kv.KV'")
	assert out.contains("pub const kv_method_get = '/kv.KV/Get'")
	assert out.contains("pub const kv_method_scan = '/kv.KV/Scan'")
	assert out.contains('pub interface KV {')
	// The request and response sides follow the streaming flags independently,
	// since a server-streamed rpc returns many messages and a client-streamed
	// one takes many requests. Collapsing every flavour onto the unary signature
	// left the streaming handlers with nowhere to put their extra messages.
	assert out.contains('get(req GetRequest) !GetResponse')
	assert out.contains('put(req PutRequest) !PutResponse')
	assert out.contains('scan(req GetRequest) ![]GetResponse')
	assert out.contains('put_many(reqs []PutRequest) !PutManyResponse')
	// The `rep` parameter was never meaningful: it was a second copy of the
	// response type on a method that also returned one.
	assert !out.contains('rep ')
}

fn test_generated_grpc_interface_is_transport_free() {
	out := generate_grpc(fixture('kv.proto'), 'kv')!
	// The file may mention `net.grpc` in its header comment, but it must not
	// import it or name one of its types in a signature. That is what lets the
	// generated file compile without the transport module, leaving the adapter
	// that registers a service to the caller.
	assert !out.contains('import net.grpc')
	assert !out.contains('ctx grpc.')
	assert !out.contains('mut ctx')
}

