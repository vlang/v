// compile_generated writes `contents` into a directory of their own and compiles
// it, failing the test with the compiler's own diagnostics if it does not build.
//
// Each case gets its own directory because they cannot share one: a directory is
// one V module, so two generated schemas in the same directory would declare
// the same module and the same structs. `-shared` is needed because generated
// code is a library with no `main`.
fn compile_generated(name string, contents []string) ! {
	dir := os.join_path(work_dir, name)
	os.rmdir_all(dir) or {}
	os.mkdir_all(dir) or { return error(err.msg()) }
	for i, content in contents {
		// Each file needs its own name: a two-file case writes a codec and a
		// service half side by side, and writing both to one path would keep
		// only the second.
		os.write_file(os.join_path(dir, '${name}_${i}.v'), content) or {
			return error(err.msg())
		}
	}
	tcc := os.join_path(os.dir(vexe), 'thirdparty', 'tcc', 'tcc.exe')
	res := os.exec([vexe, '-cc', tcc, '-shared', dir])
	if res.exit_code != 0 {
		return error('generated ${name} does not compile:\n${res.output}')
	}
}

