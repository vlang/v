fn test_write_generated_refuses_a_foreign_file() {
	// Overwriting is the one destructive thing a generator does, so a target
	// that is not generated output is reported rather than replaced.
	os.mkdir_all(work_dir)!
	target := os.join_path(work_dir, 'mine.v')
	os.write_file(target, 'fn main() {}\n')!
	if _ := write_generated(target, 'generated') {
		assert false, 'expected the write to be refused'
	} else {
		assert err.msg().contains('refusing to overwrite')
	}
	assert os.read_file(target)! == 'fn main() {}\n'
}

