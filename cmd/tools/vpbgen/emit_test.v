module main

import os

// vexe is the compiler path, used both to locate the fixtures and to compile
// generated output in the tests. `VEXE` is set by the launcher; `@VEXE` is the
// compile-time fallback.
const vexe = os.real_path(os.getenv_opt('VEXE') or { @VEXE })

// test_dir holds the .proto fixtures and the expected generated .v files.
const test_dir = os.join_path(os.dir(vexe), 'cmd', 'tools', 'vpbgen', 'tests')

// work_dir is where generated output is written during a test.
const work_dir = os.join_path(os.vtmp_dir(), 'vpbgen_test')

// fixture returns the path of a fixture file.
fn fixture(name string) string {
	return os.join_path(test_dir, name)
}

// generate parses, resolves, and emits the codec source for the schema at `path`.
fn generate(path string, module_name string) !string {
	return emit_codec(generate_res(path, module_name)!)
}

// generate_grpc returns the service source for the schema at `path`.
fn generate_grpc(path string, module_name string) !string {
	return emit_grpc(generate_res(path, module_name)!)
}

// generate_res is the parse-and-resolve step both generators share.
//
// Imports are followed, because a schema that imports another declares fields of
// the imported types and resolving it without them reports every such field as
// an unknown type. The tool does this through `load_schemas`; the tests call the
// same path so they exercise it too.
fn generate_res(path string, module_name string) !ResolvedFile {
	opts := PbgenOptions{
		module_name: module_name
		inputs:      [path]
	}
	files := load_schemas(opts)!
	res := resolve_files(files, module_name)!
	if res.errors.len > 0 {
		return error(res.errors.join_lines())
	}
	return res
}

