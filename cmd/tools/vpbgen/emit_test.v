fn test_generated_nested_message_has_presence() {
	out := generate(fixture('nested.proto'), 'demo')!
	// A singular message field has explicit presence in proto3: one set to an
	// empty message is written as an empty payload, and one never set is not
	// written at all. Writing it unconditionally made every peer see it as set.
	assert out.contains('inner ?Inner')
	assert out.contains('if inner := msg.inner {')
	assert out.contains('packer.write_message(1, inner.encode_with(opts)!)')
	// It is read through the parent's Unpacker, so the nesting depth is counted
	// and `max_depth` applies, and into what an earlier occurrence left, so two
	// occurrences merge.
	assert out.contains('mut sub := unpacker.sub()!')
	assert out.contains('sub.enter()!')
	assert out.contains('mut nested := out.inner or { Inner{} }')
	assert out.contains('read_inner(mut sub, mut nested)!')
	assert !out.contains('decode_inner(payload)')
}

fn test_generated_map_is_an_entry_message() {
	out := generate(fixture('demo.proto'), 'demo')!
	// A map is a repeated Entry message with key = 1 and value = 2.
	assert out.contains('packer.write_message(field_number, entry.bytes())')
	assert out.contains('keys.sort()')
	// Each occurrence of the field is one entry, inserted into the map that is
	// already there: a map whose entries are not adjacent on the wire still
	// decodes to all of them.
	assert out.contains('entry_key, entry_value := read_demo_map_counts_entry(mut sub)!')
	assert out.contains('out.counts[entry_key] = entry_value')
	assert !out.contains('out.counts = ')
}

fn test_generated_grpc_paths_and_interface() {
	out := generate_grpc(fixture('kv.proto'), 'kv')!
	// The path is what a client and a server agree on before any message moves.
	assert out.contains("pub const kv_service_path = '/kv.KV'")
	assert out.contains("pub const kv_method_get = '/kv.KV/Get'")
	assert out.contains("pub const kv_method_scan = '/kv.KV/Scan'")
	assert out.contains('pub interface KV {')
	// The request and response sides follow the streaming flags independently,
	// since a server-streamed rpc returns many messages and a client-streamed
	// one takes many requests. Collapsing every flavour onto the unary signature
	// left the streaming handlers with nowhere to put their extra messages.
	assert out.contains('get(req GetRequest) !GetResponse')
	assert out.contains('put(req PutRequest) !PutResponse')
	assert out.contains('scan(req GetRequest) ![]GetResponse')
	assert out.contains('put_many(reqs []PutRequest) !PutManyResponse')
	// The `rep` parameter was never meaningful: it was a second copy of the
	// response type on a method that also returned one.
	assert !out.contains('rep ')
}

fn test_generated_grpc_interface_is_transport_free() {
	out := generate_grpc(fixture('kv.proto'), 'kv')!
	// The file may mention `net.grpc` in its header comment, but it must not
	// import it or name one of its types in a signature. That is what lets the
	// generated file compile without the transport module, leaving the adapter
	// that registers a service to the caller.
	assert !out.contains('import net.grpc')
	assert !out.contains('ctx grpc.')
	assert !out.contains('mut ctx')
}

// The generated source is compiled here, not merely inspected: an emitter can
// produce plausible-looking text that does not parse, and only the compiler says
// so.
//
// There is no separate "does kv compile" or "does demo compile" case. Each of
// those fixtures is compiled by a round-trip test already, which compiles the
// same output and then runs it, so a second build of the same source would prove
// nothing and cost a nested compiler invocation. What the compile-only cases below
// add is the *file layout*: one file holding both halves, and two files in one
// directory, neither of which a round trip can express.

fn test_generated_grpc_output_compiles() {
	// The service half names the message types, so the two halves are written
	// together the way the tool writes them when `-grpc` is left at its default:
	// one file, one `module` line.
	codec := generate(fixture('kv.proto'), 'kv')!
	body := emit_grpc_body_for(fixture('kv.proto'), 'kv')!
	compile_generated('kv_both', [codec + '\n' + body])!
}

fn test_standalone_grpc_output_compiles() {
	// A separate file in the same directory is the other supported layout: V
	// treats two files declaring the same module as one module, so the service
	// half sees the codec's types without an import. Compiling the directory is
	// what proves it -- compiling one file of a multi-file module would not pull
	// in its sibling.
	codec := generate(fixture('kv.proto'), 'kv')!
	grpc := generate_grpc(fixture('kv.proto'), 'kv')!
	compile_generated('kv_split', [codec, grpc])!
}

